%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%
% If you modify this code, document all changes carefully and include date
% authorship, and a brief description of modifications
%
% Initial coding AT 01/26/2026

% Dispatch on the first subscript
switch s(1).type
    case '.'
        % A property read: nargout values, one per element of a comma list
        if nargout~=1
            % A comma list: nargout is its length (0 for an empty list;
            % an explicit subsref(P,s) statement also has 0 and returns
            % the one value as 'ans').
            [varargout{1:nargout}] = builtin('subsref',obj,s);
            if ~isempty(varargout)
                out = varargout{1};  varargout(1) = [];
            end
            return
        end
        out = builtin('subsref',obj,s);
    case '()'
        % A comma-list brace after the slice cannot be served (one output).
        for k = 2:numel(s)
            if strcmp(s(k).type,'{}') && ~all(cellfun(@(x) isscalar(x) && (isnumeric(x) || islogical(x)),s(k).subs))
                error('sopvar:parenThenList','Slice first, then read the list: Y = P(I,J); Y.field{...}.')
            end
        end
        out = op_slice(obj,s(1).subs{:});

        % Continue any further indexing on the slice, e.g. P(1,1).dims
        if numel(s)>1
            out = subsref(out,s(2:end));
        end

    case '{}'
        % Brace indexing of an operator is refused
        error('Not a valid indexing expression')
end
end
