% [out,varargout] = subsref(obj,s) indexes a sopvar object: P.name reads
% a property (a comma list, as {P.params{:}}, returns every element);
% P(I,J) returns the operator restricted to the output components I and
% the input components J (P(I) for one row or column; see 'op_slice'), and
% further indexing after the slice, as P(I,J).dims, continues on the slice;
% P{...} is an error.
%
% INPUT
% obj:  sopvar class object
% s:    struct array of subscripts, with fields 'type' ('.', '()' or '{}')
%       and 'subs', as generated by MATLAB for the expression
%
% OUTPUT
% out:  for '()', the sliced sopvar object (or the result of the indexing
%       that follows the slice); for '.', the property or the first
%       element of the comma list
% varargout: the remaining elements of a '.' comma list

